# 03 - Constraints

## Objective

To create a table using different SQL constraints to define rules and maintain data integrity.

## Task

Create a `product` table using appropriate constraints:

- `product_id` — Primary Key with Auto Increment
- `name` — NOT NULL
- `code` — UNIQUE
- `price` — CHECK condition
- `category` — ENUM
- `status` — DEFAULT value

## Constraints Used

- `PRIMARY KEY`
- `AUTO_INCREMENT`
- `NOT NULL`
- `UNIQUE`
- `CHECK`
- `DEFAULT`

## SQL Concepts Learned

- Creating named constraints
- Applying constraints while creating a table
- Defining rules for table columns
- Using `ENUM` for predefined values

